import React, { useState, useEffect } from 'react';
import { NexusSpiderAgent } from '../services/agent';
import { ExecutionResult, ValidationResult } from '../types';
import {
  ShieldAlert,
  ShieldCheck,
  Play,
  CheckCircle2,
  XCircle,
  Clock,
  Sparkles,
  FileJson,
  Table as TableIcon,
} from 'lucide-react';

interface QueryWorkbenchProps {
  agent: NexusSpiderAgent;
  onRefreshExplorer: () => void;
}

export const QueryWorkbench: React.FC<QueryWorkbenchProps> = ({ agent, onRefreshExplorer }) => {
  const [query, setQuery] = useState('SELECT * FROM users ORDER BY id ASC');
  const [validation, setValidation] = useState<ValidationResult>({ isValid: true });
  const [executionResult, setExecutionResult] = useState<ExecutionResult | null>(null);
  const [isExecuting, setIsExecuting] = useState(false);
  const [viewMode, setViewMode] = useState<'table' | 'json'>('table');

  // Validate whenever query changes
  useEffect(() => {
    const res = agent.dbManager.validateQuery(query);
    setValidation(res);
  }, [query]);

  const handleExecute = () => {
    if (!validation.isValid) return;
    setIsExecuting(true);
    try {
      const res = agent.executeQuery(query);
      setExecutionResult(res);
      onRefreshExplorer();
    } finally {
      setIsExecuting(false);
    }
  };

  const securityPresets = [
    {
      title: 'Valid SELECT Query',
      sql: 'SELECT id, name, email, age FROM users WHERE age > 25',
      expected: 'PASS',
      desc: 'Allowed operation with valid WHERE clause',
    },
    {
      title: 'Dangerous DROP DATABASE',
      sql: 'DROP DATABASE test',
      expected: 'BLOCKED',
      desc: 'Blocked by DANGEROUS_KEYWORDS filter',
    },
    {
      title: 'Multi-Statement SQL Injection',
      sql: 'SELECT * FROM users; DROP TABLE users',
      expected: 'BLOCKED',
      desc: 'Blocked by multi-statement detection (; delimiter)',
    },
    {
      title: 'Valid UPDATE Query',
      sql: 'UPDATE users SET age = 36 WHERE name = "Bob Johnson"',
      expected: 'PASS',
      desc: 'Allowed UPDATE operation with row targeting',
    },
    {
      title: 'Dangerous TRUNCATE Operation',
      sql: 'TRUNCATE TABLE users',
      expected: 'BLOCKED',
      desc: 'Blocked by DANGEROUS_KEYWORDS filter',
    },
    {
      title: 'Aggregate & Grouping',
      sql: 'SELECT category, COUNT(*) as count, SUM(stock) as total_stock, ROUND(AVG(price), 2) as avg_price FROM products GROUP BY category',
      expected: 'PASS',
      desc: 'Advanced SELECT with aggregation',
    },
  ];

  return (
    <div className="max-w-7xl mx-auto space-y-6">
      {/* Top Banner explaining Nexus Spider Security Engine */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center space-x-2">
            <ShieldCheck className="w-5 h-5 text-emerald-400" />
            <h2 className="text-base font-semibold text-white">
              Nexus Spider Security &amp; SQL Injection Shield
            </h2>
          </div>
          <p className="text-xs text-slate-400 mt-1 max-w-3xl">
            Every query (whether typed manually or generated by LM Studio) passes through the built-in
            validation engine before execution. Dangerous statements, multi-query injections, and unauthorized
            operations are blocked at the perimeter.
          </p>
        </div>

        {/* Real-time status */}
        <div
          className={`flex items-center space-x-2 px-3 py-1.5 rounded-lg border text-xs font-mono font-medium ${
            validation.isValid
              ? 'bg-emerald-950/50 border-emerald-800/80 text-emerald-400'
              : 'bg-red-950/50 border-red-800/80 text-red-400'
          }`}
        >
          {validation.isValid ? (
            <>
              <CheckCircle2 className="w-4 h-4" />
              <span>QUERY VALID &amp; SAFE</span>
            </>
          ) : (
            <>
              <ShieldAlert className="w-4 h-4" />
              <span>BLOCKED: {validation.error}</span>
            </>
          )}
        </div>
      </div>

      {/* Main Grid: Editor & Security Checks */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* SQL Editor Area (2 cols) */}
        <div className="lg:col-span-2 bg-slate-900 border border-slate-800 rounded-xl overflow-hidden flex flex-col">
          <div className="px-4 py-3 bg-slate-900/80 border-b border-slate-800 flex items-center justify-between">
            <span className="text-xs font-mono font-semibold text-slate-300">SQL Query Editor</span>
            <div className="flex items-center space-x-2">
              <button
                onClick={handleExecute}
                disabled={!validation.isValid || isExecuting}
                className="px-4 py-1.5 bg-cyan-600 hover:bg-cyan-500 disabled:opacity-50 disabled:cursor-not-allowed text-white text-xs font-semibold rounded-lg flex items-center space-x-1.5 transition shadow"
              >
                <Play className="w-3.5 h-3.5" />
                <span>Execute Query</span>
              </button>
            </div>
          </div>

          <div className="p-4 bg-slate-950 flex-1">
            <textarea
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              rows={6}
              className="w-full bg-transparent text-xs sm:text-sm font-mono text-cyan-300 outline-none resize-none leading-relaxed"
              placeholder="Enter SQLite query (e.g. SELECT * FROM users)..."
            />
          </div>

          {/* Preset Security Test Queries */}
          <div className="p-3 bg-slate-900 border-t border-slate-800">
            <div className="text-[11px] text-slate-400 font-semibold mb-2 flex items-center space-x-1">
              <Sparkles className="w-3 h-3 text-cyan-400" />
              <span>Security Validation Presets (from demo_without_llm.py):</span>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
              {securityPresets.map((preset, idx) => (
                <button
                  key={idx}
                  onClick={() => setQuery(preset.sql)}
                  className="text-left p-2 rounded-lg bg-slate-950/70 hover:bg-slate-800 border border-slate-800/80 hover:border-slate-700 transition"
                >
                  <div className="flex items-center justify-between">
                    <span className="text-xs font-medium text-slate-200">{preset.title}</span>
                    <span
                      className={`text-[10px] font-mono px-1.5 py-0.5 rounded ${
                        preset.expected === 'PASS'
                          ? 'bg-emerald-950 text-emerald-400 border border-emerald-800/40'
                          : 'bg-red-950 text-red-400 border border-red-800/40'
                      }`}
                    >
                      {preset.expected}
                    </span>
                  </div>
                  <p className="text-[10px] text-slate-400 font-mono truncate mt-1">{preset.sql}</p>
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* Security Inspector Checklist (1 col) */}
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 flex flex-col justify-between">
          <div>
            <h3 className="font-semibold text-sm text-white mb-3 flex items-center space-x-2">
              <ShieldCheck className="w-4 h-4 text-cyan-400" />
              <span>Inspection Breakdown</span>
            </h3>

            <div className="space-y-3.5 text-xs">
              {/* Check 1: Allowed Operations */}
              <div className="p-3 rounded-lg bg-slate-950 border border-slate-800">
                <div className="flex items-center justify-between mb-1">
                  <span className="font-semibold text-slate-300">1. Allowed Operation</span>
                  {validation.details?.firstWord &&
                  ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'CREATE', 'ALTER', 'DROP'].includes(
                    validation.details.firstWord
                  ) ? (
                    <span className="text-emerald-400 font-mono text-[11px] flex items-center space-x-1">
                      <CheckCircle2 className="w-3.5 h-3.5" />
                      <span>{validation.details.firstWord}</span>
                    </span>
                  ) : (
                    <span className="text-red-400 font-mono text-[11px] flex items-center space-x-1">
                      <XCircle className="w-3.5 h-3.5" />
                      <span>REJECTED</span>
                    </span>
                  )}
                </div>
                <p className="text-[11px] text-slate-500">
                  Must start with SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, or DROP.
                </p>
              </div>

              {/* Check 2: Multi-Statement Injection */}
              <div className="p-3 rounded-lg bg-slate-950 border border-slate-800">
                <div className="flex items-center justify-between mb-1">
                  <span className="font-semibold text-slate-300">2. Multiple Statement Check</span>
                  {query.trim().replace(/;+\s*$/, '').includes(';') ? (
                    <span className="text-red-400 font-mono text-[11px] flex items-center space-x-1">
                      <XCircle className="w-3.5 h-3.5" />
                      <span>INJECTION DETECTED</span>
                    </span>
                  ) : (
                    <span className="text-emerald-400 font-mono text-[11px] flex items-center space-x-1">
                      <CheckCircle2 className="w-3.5 h-3.5" />
                      <span>CLEAN</span>
                    </span>
                  )}
                </div>
                <p className="text-[11px] text-slate-500">
                  Prevents compound statement attacks (e.g. `; DROP TABLE ...`).
                </p>
              </div>

              {/* Check 3: Dangerous Keywords */}
              <div className="p-3 rounded-lg bg-slate-950 border border-slate-800">
                <div className="flex items-center justify-between mb-1">
                  <span className="font-semibold text-slate-300">3. Dangerous Keywords Scan</span>
                  {validation.details?.hasDangerousKeyword ? (
                    <span className="text-red-400 font-mono text-[11px] flex items-center space-x-1">
                      <XCircle className="w-3.5 h-3.5" />
                      <span>{validation.details.dangerousKeyword}</span>
                    </span>
                  ) : (
                    <span className="text-emerald-400 font-mono text-[11px] flex items-center space-x-1">
                      <CheckCircle2 className="w-3.5 h-3.5" />
                      <span>NO BLOCKED KEYWORDS</span>
                    </span>
                  )}
                </div>
                <p className="text-[11px] text-slate-500">
                  Blocks DROP DATABASE, TRUNCATE, GRANT, REVOKE, ALTER SYSTEM.
                </p>
              </div>
            </div>
          </div>

          <div className="mt-4 pt-3 border-t border-slate-800 text-[11px] text-slate-400 flex items-center space-x-1.5">
            <Clock className="w-3.5 h-3.5 text-cyan-400" />
            <span>Parameterized execution supported</span>
          </div>
        </div>
      </div>

      {/* Execution Results View */}
      {executionResult && (
        <div className="bg-slate-900 border border-slate-800 rounded-xl overflow-hidden">
          <div className="px-5 py-3.5 border-b border-slate-800 flex items-center justify-between bg-slate-900/80">
            <div className="flex items-center space-x-3">
              <span
                className={`text-xs font-mono font-semibold px-2 py-0.5 rounded ${
                  executionResult.success
                    ? 'bg-emerald-950 text-emerald-400 border border-emerald-800/40'
                    : 'bg-red-950 text-red-400 border border-red-800/40'
                }`}
              >
                {executionResult.success ? 'SUCCESS' : 'EXECUTION FAILED'}
              </span>
              <span className="text-xs text-slate-300">{executionResult.message}</span>
              {executionResult.durationMs !== undefined && (
                <span className="text-xs text-slate-500 font-mono">
                  ({executionResult.durationMs}ms)
                </span>
              )}
            </div>

            {executionResult.results && executionResult.results.length > 0 && (
              <div className="flex items-center space-x-1 bg-slate-950 p-0.5 rounded-lg border border-slate-800">
                <button
                  onClick={() => setViewMode('table')}
                  className={`p-1.5 rounded text-xs transition ${
                    viewMode === 'table' ? 'bg-slate-800 text-cyan-400' : 'text-slate-400 hover:text-white'
                  }`}
                  title="Table view"
                >
                  <TableIcon className="w-3.5 h-3.5" />
                </button>
                <button
                  onClick={() => setViewMode('json')}
                  className={`p-1.5 rounded text-xs transition ${
                    viewMode === 'json' ? 'bg-slate-800 text-cyan-400' : 'text-slate-400 hover:text-white'
                  }`}
                  title="JSON view"
                >
                  <FileJson className="w-3.5 h-3.5" />
                </button>
              </div>
            )}
          </div>

          <div className="p-4 max-h-96 overflow-auto bg-slate-950">
            {executionResult.results && executionResult.results.length > 0 ? (
              viewMode === 'table' ? (
                <table className="w-full text-left text-xs font-mono border-collapse">
                  <thead className="bg-slate-900 text-slate-300 sticky top-0">
                    <tr>
                      {Object.keys(executionResult.results[0]).map((key) => (
                        <th key={key} className="px-3 py-2 border-b border-slate-800 font-semibold">
                          {key}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800">
                    {executionResult.results.map((row, rIdx) => (
                      <tr key={rIdx} className="hover:bg-slate-900/50">
                        {Object.keys(executionResult.results![0]).map((key) => (
                          <td key={key} className="px-3 py-1.5 text-slate-300 whitespace-nowrap">
                            {row[key] !== null && row[key] !== undefined
                              ? String(row[key])
                              : <span className="text-slate-600 italic">null</span>}
                          </td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              ) : (
                <pre className="text-xs font-mono text-emerald-400 leading-relaxed whitespace-pre-wrap">
                  {JSON.stringify(executionResult.results, null, 2)}
                </pre>
              )
            ) : (
              <div className="text-xs text-slate-400 font-mono py-2">
                {executionResult.success
                  ? `Rows affected: ${executionResult.rowsAffected ?? 0}`
                  : executionResult.message}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
